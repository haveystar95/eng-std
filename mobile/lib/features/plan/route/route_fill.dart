/// ЛИНИЯ МАРШРУТА = ПРОГРЕСС (канва PLAN-DES-3, эталон заливки — кадры 21-2 и 21-2b).
///
/// Маршрут — одна линия через узлы дней (картинка 56) и узлы их этапов (14). Отрезок между
/// соседними узлами бывает трёх цветов, и правило одно на все экраны:
///
/// - ШАЛФЕЙ — до последнего пройденного узла включительно;
/// - ЛАТУНЬ — отрезок, который входит в ТЕКУЩИЙ этап;
/// - СЕРЫЙ — всё дальше.
///
/// «Пройден» у этапа — это `done` с сервера. У узла дня — «до него дошли»: день открыт сегодня,
/// идёт, закрыт, или закрыт день перед ним (21-4: день 2 закрыт, день 3 откроется завтра — линия
/// шалфеем доходит до картинки дня 3 и дальше серая, латуни на экране нет). Клиент ничего не
/// выводит о самих этапах: их состояние пришло словом, и этот файл только красит отрезки.
library;

/// Цвет одного отрезка линии.
enum RouteSegment { walked, current, ahead }

/// Что про узел известно для заливки.
class RouteFillNode {
  const RouteFillNode({required this.passed, this.current = false});

  /// Узел пройден (этап `done`) или до него дошли (узел дня — см. выше).
  final bool passed;

  /// Узел — текущий этап (`current`).
  final bool current;
}

/// Отрезки между соседними узлами: `result[i]` соединяет `nodes[i]` и `nodes[i + 1]`.
///
/// Пройденным считается только НЕПРЕРЫВНЫЙ префикс: пройденный узел после непройденного линию не
/// заливает — прогресс на маршруте не бывает с дырами.
List<RouteSegment> routeSegments(List<RouteFillNode> nodes) {
  var lastWalked = -1;
  while (lastWalked + 1 < nodes.length && nodes[lastWalked + 1].passed) {
    lastWalked++;
  }

  return [
    for (var i = 0; i < nodes.length - 1; i++)
      if (i < lastWalked)
        RouteSegment.walked
      else if (i == lastWalked && nodes[i + 1].current)
        RouteSegment.current
      else
        RouteSegment.ahead,
  ];
}
