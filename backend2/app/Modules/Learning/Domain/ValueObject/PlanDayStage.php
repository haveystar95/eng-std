<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\ValueObject;

use App\Modules\Learning\Domain\Service\PlanSessionSections;

/**
 * ЭТАПЫ ДНЯ — «Слова и фразы» → «Разговор» → «Скажи сам», и «Повторить ошибки» сбоку
 * (наряд DAY-GATE-1, Ч.1.1; решение владельца 07.09).
 *
 * Живой прогон 07.09 показал день, у которого не было видно ни из чего он состоит, ни где человек
 * сейчас: экран говорил «идёт», кнопка «Продолжить» вела в пустую сессию, а прогон голосом не
 * предлагался ни разу. Причина была одна на все три симптома — у дня не было ЭТАПОВ. Была посадка
 * («материал» и «разговор» как два потолка бюджета) и была лестница карточек (A/B/C), и ни то ни
 * другое не отвечало на вопрос «что мне осталось до конца дня».
 *
 * ## Три обязательных и одно необязательное
 *
 *   {@see Material}      «Слова и фразы» — всё, с чем человек ЗНАКОМИТСЯ: разогрев, слова, связки,
 *                        знакомство с репликами и упражнения к ним (ступень A);
 *   {@see Conversation}  «Разговор» — всё, что человек ГОВОРИТ в разговоре: ступень B реплик сцены,
 *                        своей и шва;
 *   {@see Rehearsal}     «Скажи сам» — та же сцена голосом, без текста на экране;
 *   {@see Retrain}       «Повторить ошибки» — необязательный, день не держит, в {@see REQUIRED} не
 *                        входит.
 *
 * ## «Пройден» значит ПРОЙДЕН НАСКВОЗЬ, а не «закрыт по лестнице»
 *
 * Решение владельца 07.09 и главное, что стоит помнить об этом типе: этап пройден, когда все его
 * карточки ПОКАЗАНЫ И ОТВЕЧЕНЫ — верно или нет. Лестница реплики (A/B/C) и прохождение дня — разные
 * вещи: лестница это проекция журнала, «сколько эта пара ещё не умеет», а прохождение — факт, что
 * человек дошёл до конца этапа. Реплика, сказанная неверно, день НЕ держит: по правилу «один показ
 * ступени в день» она вернётся завтра — в разогреве и в шве, — а сегодня этап на ней закончился.
 *
 * Раньше было наоборот, и это стоило владельцу вечера: три реплики, отвеченные неверно, оставили
 * день 1 незакрытым, посадка стала пустой (лестница им сегодня ничего не должна), и «Продолжить»
 * вело в «здесь пока нечего повторять» над днём, который сам себя считал идущим.
 *
 * ## Порядок — не украшение
 *
 * Прогон голосом идёт ПОСЛЕ разговора, потому что говорить по памяти реплику, которую ни разу не
 * выбирал, — это не сложная карточка, а неотвечаемая (`docs/plan-dialogue.md` §5). Но зрелость
 * сцены прогон больше не гейтит: как только «Разговор» пройден насквозь, «Скажи сам» собирается
 * ВСЕГДА. В прогоне несказанная реплика — законный ход: «Пропустить» и спасатель на месте, промах
 * ничего не ломает.
 */
enum PlanDayStage: string
{
    /** «Слова и фразы» — знакомство и упражнения к нему. */
    case Material = 'material';

    /** «Разговор» — реплики сцены на ступени B. */
    case Conversation = 'conversation';

    /** «Скажи сам» — прогон сцены голосом. */
    case Rehearsal = 'rehearsal';

    /** «Повторить ошибки» — необязательный этап, день не держит. */
    case Retrain = 'retrain';

    /**
     * ТРИ ЭТАПА, КОТОРЫЕ ДЕНЬ ОБЯЗАН ПРОЙТИ, по порядку. «День пройден» = все три пройдены насквозь,
     * и другого определения «дня пройден» в коде нет.
     *
     * @var list<self>
     */
    public const REQUIRED = [self::Material, self::Conversation, self::Rehearsal];

    /**
     * ЭТАП, КОТОРОМУ ПРИНАДЛЕЖИТ КАРТОЧКА ЭТОЙ СЕКЦИИ.
     *
     * Секции ({@see PlanSessionSections}) остаются единственным словарём частей посадки, а этап —
     * их укрупнение: знакомство с репликой это ещё «Слова и фразы», диалог — «Разговор», прогон —
     * «Скажи сам». Ключ секции приходит либо голым кодом, либо в виде `<код>#<день>`, как его
     * ключует планировщик.
     */
    public static function ofSection(string $sectionKey): self
    {
        $code = explode('#', $sectionKey, 2)[0];

        return match ($code) {
            PlanSessionSections::DIALOGUE => self::Conversation,
            PlanSessionSections::SCENE_RUN, PlanSessionSections::REHEARSAL => self::Rehearsal,
            default => self::Material,
        };
    }

    /** Этап, после которого открывается этот. Null у первого — ему нечего ждать. */
    public function opensAfter(): ?self
    {
        return match ($this) {
            self::Material, self::Retrain => null,
            self::Conversation => self::Material,
            self::Rehearsal => self::Conversation,
        };
    }
}
