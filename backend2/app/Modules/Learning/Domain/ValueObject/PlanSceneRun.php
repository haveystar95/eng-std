<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\ValueObject;

/**
 * ОДИН ЗАВЕРШЁННЫЙ ПРОГОН СЦЕНЫ — наряд SCENE-RUN, Ч.2.6.
 *
 * Ступень C канона: реплики на экране нет, есть подсказка на языке поддержки и микрофон. Строка
 * пишется РАЗ на завершённый прогон и не редактируется — это событие, а не счётчик.
 *
 * ## Четыре числа, и они не пересекаются
 *
 * `total` = `said` + `skipped` + `rescued`, где:
 *
 *   said     ключ реплики прозвучал голосом человека;
 *   skipped  человек нажал «Пропустить» или сторож сделал это за него;
 *   rescued  ход сделал спасатель — не ошибка и не «сам» (канон §8: «их использование не ошибка,
 *            а нормальный ход»), поэтому третье число, а не разновидность одного из двух.
 *
 * `saidFast` — подмножество `said`: ключ прозвучал в первые секунды прослушивания
 * (`config/learning.php → plan.scene_run.fast_seconds`). Это вторая половина «готовности» канона
 * §4, и она СЧИТАЕТСЯ ОТДЕЛЬНО от «сказал», потому что медленный успех остаётся успехом.
 *
 * Процентов здесь нет и на экранах плана не будет: итог читается словами — «Прошёл сам N из M ·
 * сразу K» (кадр DL·10).
 */
final readonly class PlanSceneRun
{
    public function __construct(
        public string $planId,
        /** Индекс СЦЕНЫ — он же индекс дня, который её ввёл: день плана это одна сцена целиком. */
        public int $sceneIndex,
        /** День, В КОТОРОМ прогон случился. Совпадает со сценой в обычный день и расходится в финальном. */
        public int $dayIndex,
        public int $total,
        public int $said,
        public int $saidFast,
        public int $skipped,
        public int $rescued,
    ) {}

    /** Прогон, в котором человек прошёл сам каждый ход. Не «готов» — про скорость это не говорит. */
    public function allSaid(): bool
    {
        return $this->total > 0 && $this->said === $this->total;
    }

    /** Доля «сразу» среди ВСЕХ ходов сцены, а не среди сказанных: пропуск это не полскорости. */
    public function fastShare(): float
    {
        return $this->total === 0 ? 0.0 : $this->saidFast / $this->total;
    }
}
