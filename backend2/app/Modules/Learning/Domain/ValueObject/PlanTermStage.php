<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\ValueObject;

/**
 * ЧТО ПАРА (ПЛАН, ТЕРМИН) ДОКАЗАЛА ГОЛОСОМ — два факта, которых нет в журнале ответов.
 *
 * Лестница плана считается по append-only журналу и не хранится нигде
 * ({@see \App\Modules\Learning\Domain\Service\PlanStageLadder}), и это правило цело: строгость
 * хода тоже выводится — из места шага в чек-листе ({@see PlanTurnLevel::forStep()}), — и хранить
 * для неё нечего.
 *
 * Здесь только то, чего журнал не знает и знать не может, потому что журнал хранит РЕЖИМ и ВЕРДИКТ,
 * а эти два факта про то, что случилось ВНУТРИ одной карточки прогона:
 *
 *   {@see $saidInRun}   реплика прозвучала голосом человека в прогоне сцены — ступень C.
 *   {@see $saidFast}    …и прозвучала СРАЗУ (наряд SCENE-RUN, Ч.2, порог в `config/learning.php`).
 *                       Готовность канона — это «C + скорость» (`docs/plan-model.md` §4), и
 *                       скорость здесь не латентность карточки, а время до ключа внутри одного
 *                       прослушивания: карточка успела бы сойтись и за пятнадцать секунд.
 *
 * Ключ — ПАРА (план, термин), а не (пользователь, термин): термины дедуплицированы глобально, и
 * «сказал сам» в прошлом плане не является доказательством про этот. Прогресс пула
 * (`user_term_progress`) здесь не участвует вовсе и этой строкой не двигается.
 *
 * Обновляется ЛУЧШИМ результатом: один раз сказал сам — сказал сам. Прогон, в котором ту же реплику
 * пропустили, не отнимает у неё того, что было; отнимать умеет только человек, начав план заново.
 */
final readonly class PlanTermStage
{
    public function __construct(
        public string $planId,
        public string $termId,
        /** Ключ реплики прозвучал голосом человека хотя бы в одном прогоне сцены. */
        public bool $saidInRun = false,
        /** …и хотя бы раз — в первые секунды прослушивания. */
        public bool $saidFast = false,
        /**
         * ЛОКАЛЬНЫЙ ДЕНЬ, В КОТОРЫЙ РЕПЛИКУ УЖЕ БРАЛИ «ПОВТОРИТЬ ОШИБКИ» (наряд DAY-GATE-1).
         *
         * Третий факт, которого нет в журнале, и по той же причине, что и первые два: журнал хранит
         * режим и вердикт, а это про то, ОТКУДА взялась карточка. Очередь посадки на телефоне
         * переспрашивает промах в той же сессии и пишет за него ответ, так что по числу ответов
         * повтор по кнопке от переспроса очереди не отличить.
         *
         * Один дополнительный показ в день, и дата — это то, что делает «в день» правдой без ночной
         * уборки. `Y-m-d` в часовом поясе учащегося; null — сегодня ещё не брали.
         */
        public ?string $retrainedOn = null,
    ) {}

    /** Тот же факт после хода в прогоне сцены — лучшим результатом, никогда не хуже. */
    public function afterRun(bool $said, bool $fast): self
    {
        return new self(
            $this->planId,
            $this->termId,
            $this->saidInRun || $said,
            $this->saidFast || ($said && $fast),
            $this->retrainedOn,
        );
    }

    /** Реплику взяли «Повторить ошибки» сегодня — больше сегодня её этой дверью не выдать. */
    public function afterRetrain(string $today): self
    {
        return new self($this->planId, $this->termId, $this->saidInRun, $this->saidFast, $today);
    }

    /** Брали ли её этой дверью СЕГОДНЯ. */
    public function retrainedOn(string $today): bool
    {
        return $this->retrainedOn === $today;
    }
}
