<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\ValueObject;

/**
 * СТРОГОСТЬ ТВОЕГО ХОДА в диалоге сцены — `docs/plan-dialogue.md` §5, три уровня одной ступени.
 *
 * Не режим и не тренажёр. Тренажёр всё это время один — ситуационная карточка
 * ({@see ExerciseMode::SituationalSay} / {@see ExerciseMode::SituationalAsk}), — а это то, СКОЛЬКО
 * с экрана убрали к моменту, когда ход передают человеку:
 *
 *   choose    три-четыре реальные реплики плана, одна подходит. Это то, что продаётся, и оно
 *             обязано ощущаться игрой (канон §5: «C никогда не первый: страшно»).
 *   assemble  вариантов нет, есть блоки — слова и связки самой реплики плюс 2–4 чужих. Клавиатуры
 *             нет никогда и ни на каком уровне (канон §9, железное правило продукта).
 *   say       на экране только подсказка на языке поддержки и микрофон. Живёт в прогоне сцены
 *             (наряд SCENE-RUN, Ч.2), а не в обычном диалоге.
 *
 * ПОЧЕМУ ЭТО НЕ НОВЫЕ ЗНАЧЕНИЯ {@see ExerciseMode}. Режим — строка реестра «Тренажёры», которую
 * владелец включает себе, потом бете, потом всем, и у которой есть глобальная матрица допуска.
 * Уровень строгости включать нечего: он не выбирается, он НАСТУПАЕТ, когда пара доказала выбором,
 * что вариантов ей уже мало ({@see \App\Modules\Learning\Domain\Service\PlanDialogueLevel}). Завести
 * ему строку в матрице значило бы разрешить состояние «сборка выключена» — то есть ступень B, из
 * которой нет выхода.
 */
enum PlanTurnLevel: string
{
    /** B · выбор — три-четыре реплики плана, тап. */
    case Choose = 'choose';

    /** B+ · сборка — блоки реплики и дистракторы, тап по блокам, кнопка «Проверить». */
    case Assemble = 'assemble';

    /** C · сам — подсказка и микрофон, реплики на экране нет (прогон сцены). */
    case Say = 'say';
}
