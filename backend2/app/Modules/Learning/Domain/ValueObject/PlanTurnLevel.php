<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\ValueObject;

/**
 * СТРОГОСТЬ ТВОЕГО ХОДА в диалоге сцены — `docs/plan-dialogue.md` §5, три уровня одной ступени.
 *
 * Не режим и не тренажёр. Тренажёр всё это время один — ситуационная карточка
 * ({@see ExerciseMode::SituationalSay} / {@see ExerciseMode::SituationalAsk}), — а это то, СКОЛЬКО
 * с экрана убрали к моменту, когда ход передают человеку:
 *
 *   choose    три-четыре реальные реплики плана, одна подходит. Это то, что продаётся, и оно
 *             обязано ощущаться игрой (канон §5: «C никогда не первый: страшно»).
 *   assemble  вариантов нет, есть блоки — слова и связки самой реплики плюс 2–4 чужих. Клавиатуры
 *             нет никогда и ни на каком уровне (канон §9, железное правило продукта).
 *   say       на экране только подсказка на языке поддержки и микрофон. Живёт в прогоне сцены
 *             (наряд SCENE-RUN, Ч.2), а не в обычном диалоге.
 *
 * ПОЧЕМУ ЭТО НЕ НОВЫЕ ЗНАЧЕНИЯ {@see ExerciseMode}. Режим — строка реестра «Тренажёры», которую
 * владелец включает себе, потом бете, потом всем, и у которой есть глобальная матрица допуска.
 * Уровень строгости включать нечего: он не выбирается, он НАСТУПАЕТ ({@see forTurn()}). Завести ему
 * строку в матрице значило бы разрешить состояние «сборка выключена» — то есть ступень B, из
 * которой нет выхода.
 */
enum PlanTurnLevel: string
{
    /** B · выбор — три-четыре реплики плана, тап. */
    case Choose = 'choose';

    /** B+ · сборка — блоки реплики и дистракторы, тап по блокам, кнопка «Проверить». */
    case Assemble = 'assemble';

    /** C · сам — подсказка и микрофон, реплики на экране нет (прогон сцены). */
    case Say = 'say';

    /** `terms.shelf` полки «Ты спросишь» — литерал, потому что Domain не импортирует Generation. */
    public const SHELF_ASK = 'ask';

    /**
     * УРОВЕНЬ ХОДА ПО ЕГО МЕСТУ В ЧЕК-ЛИСТЕ СТУПЕНИ B — первое касание выбирают, следующее собирают.
     *
     * Сборка привязана к ПОВТОРНОМУ ПОЯВЛЕНИЮ реплики, а не к счётчику удач: выбор закрывается одним
     * верным ответом, и реплика, вернувшись — в хвост присеста, в шов следующего дня, — показывается
     * сборкой, потому что первый шаг уже закрыт. Ничего для этого не хранится: место в чек-листе и
     * есть ответ, а чек-лист — проекция append-only журнала
     * ({@see \App\Modules\Learning\Domain\Service\PlanStageLadder}).
     *
     * Ошибка на сборке ступень не открывает и в выбор не откатывает: второй шаг остаётся
     * незакрытым, и следующая раздача — снова он, снова сборкой.
     *
     * @param  int  $ordinal  место шага в чек-листе ступени, с единицы
     */
    public static function forStep(int $ordinal): self
    {
        return $ordinal <= 1 ? self::Choose : self::Assemble;
    }

    /**
     * УРОВЕНЬ ХОДА С ДВУМЯ ЗАМКАМИ ПОВЕРХ МЕСТА В ЧЕК-ЛИСТЕ (наряд DAY-FIX-2, Ч.1.4 и Ч.2.3).
     *
     *   «Ты спросишь» — НИКОГДА не выбор. Живой прогон 05.09: четыре одинаково уместных вопроса, и
     *   «правильного» среди них нет по смыслу — вопрос человек ставит сам, а не узнаёт среди чужих.
     *   Уровень у вопроса начинается со сборки и кончается голосом.
     *
     *   Шов — НИКОГДА не выбор. Реплика из дней позади возвращается одним касанием, сборкой: выбор
     *   был её первым появлением на ступени, и повторять его на третий день значило бы гонять
     *   человека по тому, что он уже выбрал. Замок нужен отдельно от места в чек-листе, потому что
     *   выбор, отвеченный НЕВЕРНО в свой день, оставляет первый шаг открытым — и без замка вернулся
     *   бы выбором.
     *
     * @param  string|null  $shelf  полка хода — `say` или `ask`
     * @param  int  $ordinal  место шага в чек-листе ступени, с единицы
     * @param  bool  $inSeam  ход раздаётся из дня позади того, который изучают
     */
    public static function forTurn(?string $shelf, int $ordinal, bool $inSeam = false): self
    {
        if ($shelf === self::SHELF_ASK || $inSeam) {
            return self::Assemble;
        }

        return self::forStep($ordinal);
    }
}
