<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\ValueObject;

/**
 * ЧТО СКАЗАТЬ ЧЕЛОВЕКУ ПРО ЕГО РЕПЛИКУ — три слова и ни одним больше (наряд SPEECH-2, Ч.3.5).
 *
 *   correct  «верно» — сказано достаточно;
 *   almost   «почти — не хватило: …» — реплика узнана, но часть слов не прозвучала. НЕ зачёт:
 *            в журнал уходит тот же `again`, что и у промаха. Отдельным словом она стоит потому,
 *            что «не то» на реплике, из которой не хватило одного слова, — это неправда, и человек,
 *            услышавший её трижды, перестаёт говорить вслух;
 *   wrong    «не то» — сказано не это.
 *
 * Почему не {@see \App\Modules\Learning\Domain\ValueObject\Grade}: оценка — это то, что видит
 * планировщик, и у неё четыре ступени про ПАМЯТЬ. Это — то, что видит человек, и оно про РЕЧЬ.
 * Смешивать их значит либо завести планировщику пятую ступень, которой он не умеет пользоваться,
 * либо молча выкинуть «почти».
 */
enum SpokenCredit: string
{
    case Correct = 'correct';
    case Almost = 'almost';
    case Wrong = 'wrong';

    /** Зачёт — и только он. «Почти» зачётом не является ни на экране, ни в журнале. */
    public function isAccepted(): bool
    {
        return $this === self::Correct;
    }
}
