<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\ValueObject;

/**
 * В КАКОМ СОСТОЯНИИ ЭТАП ДНЯ — три слова и не больше (наряд DAY-GATE-1, Ч.1.1).
 *
 * Кодами на провод, словами на экране: «пройдено» · «сейчас» · «после разговора». Четвёртого
 * состояния нет сознательно — «этап, по которому сегодня больше нечего дать, но он не кончился» это
 * ровно то, чего решение владельца 07.09 не оставило: этап, все карточки которого показаны, ПРОЙДЕН.
 */
enum PlanDayStageState: string
{
    /** Пройден насквозь: все карточки этапа показаны и отвечены. */
    case Done = 'done';

    /** Тот, в который ведёт «Продолжить». Ровно один на день, пока день не пройден. */
    case Current = 'current';

    /** Ещё закрыт — откроется после {@see PlanDayStage::opensAfter()}. */
    case Locked = 'locked';
}
