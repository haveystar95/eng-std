<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\ValueObject;

/**
 * ЗРЕЛОСТЬ СЦЕНЫ — три слова, которыми продукт говорит о материале (`docs/plan-dialogue.md` §2).
 *
 * «Познакомился → применяю → говорю сам». Это язык, на котором о плане говорит ПРОДУКТ; «ступень
 * A», «rung», «stage» — язык, на котором о нём говорит код, и на экранах его нет нигде (наряд
 * DAY-2-FIX, Ч.2.1 и Ч.3а).
 *
 * До наряда SCENE-RUN состояний было два из трёх, и это признавалось вслух: «говоришь сам» требует
 * переписи ступени C, а её на проводе не было, и выводить вердикт из данных, которых нет, — это
 * ровно тот процент, который владелец три дня читал нулём. Теперь ступень C есть
 * ({@see PlanTermStage::$saidInRun}), и третье слово наступает по факту, а не по надежде.
 */
enum SceneMaturity: string
{
    /** Человек встретил реплики сцены. Ступень A — знакомство. */
    case Met = 'met';

    /** Человек ВЫБИРАЕТ реплики в разговоре: каждый его ход прошёл ступень B хотя бы раз. */
    case Applying = 'applying';

    /** Человек говорит сцену САМ: каждый его ход прозвучал голосом в прогоне. */
    case Speaking = 'speaking';
}
