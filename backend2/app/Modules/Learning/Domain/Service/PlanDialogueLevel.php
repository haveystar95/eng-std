<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\Service;

use App\Modules\Learning\Domain\ValueObject\PlanTurnLevel;

/**
 * КОГДА ХОД ПЕРЕСТАЁТ БЫТЬ ВЫБОРОМ И СТАНОВИТСЯ СБОРКОЙ — наряд SCENE-RUN, Ч.1.
 *
 * Канон (`docs/plan-dialogue.md` §5): «B → B+ когда выбор закрыт без ошибок дважды». Здесь это
 * сказано механически: у пары (план, термин) есть счётчик безошибочных ВЫБОРОВ подряд, и на
 * {@see CHOICES_FOR_ASSEMBLY} ход переходит на сборку.
 *
 * ## Почему счётчик хранится, а не выводится из журнала
 *
 * Всё остальное про прогресс здесь — проекция append-only журнала, и это правильно. Этот счётчик —
 * исключение ровно из-за одного пункта наряда: «Ошибка на сборке НЕ откатывает в choose». Сборка и
 * выбор пишутся В ЖУРНАЛ ОДНИМ И ТЕМ ЖЕ режимом (тренажёр один, уровень — это подача), поэтому по
 * журналу их не различить: неверная сборка выглядела бы неверным выбором и сбросила бы счётчик,
 * то есть отобрала бы у человека сборку за то, что он её не сдал с первого раза. Хранимый счётчик
 * различает их даром — {@see after()} читает СВОЁ ЖЕ прошлое значение и по нему знает, чем была
 * раздача.
 *
 * ## Ступень не зависает
 *
 * Третье касание ступени B раздаётся всегда — сборкой, если счётчик дозрел, и выбором, если нет
 * ({@see forStreak()}). Иначе пара, которая один раз ошиблась, никогда не набрала бы двух подряд и
 * осталась бы на ступени B навсегда: незакрываемый шаг — это непроходимый день.
 */
final class PlanDialogueLevel
{
    /**
     * Сколько безошибочных выборов подряд открывают сборку.
     *
     * Два, а не один: один верный выбор из трёх — это ещё и удача. Два подряд — уже не удача, и
     * канон называет именно это число.
     */
    public const CHOICES_FOR_ASSEMBLY = 2;

    /** Уровень следующей раздачи хода при таком счётчике. */
    public static function forStreak(int $streak): PlanTurnLevel
    {
        return $streak >= self::CHOICES_FOR_ASSEMBLY ? PlanTurnLevel::Assemble : PlanTurnLevel::Choose;
    }

    /**
     * Счётчик ПОСЛЕ ответа на ход, раздан он был выбором или сборкой.
     *
     * Раздача была сборкой ровно тогда, когда счётчик уже дозрел, — и тогда ответ его не трогает
     * вовсе: ни верная сборка (счётчик уже сделал своё дело), ни неверная (иначе ход откатился бы в
     * выбор, что наряд запрещает прямо).
     */
    public static function after(int $streak, bool $correct): int
    {
        if ($streak >= self::CHOICES_FOR_ASSEMBLY) {
            return $streak;
        }

        return $correct ? $streak + 1 : 0;
    }
}
