<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\Service;

use App\Modules\Learning\Domain\ValueObject\SituationalCandidate;

/**
 * ИЗ ЧЕГО СОБИРАЮТСЯ ВАРИАНТЫ ТВОЕГО ХОДА — наряд DAY-2-FIX, Ч.1.5.
 *
 * Живой прогон владельца показал два дефекта в одном списке вариантов, и оба делают выбор
 * бессмысленным ещё до того, как человек прочитает хоть одну строку.
 *
 * ## 1. Реплика собеседника не может быть твоим ответом
 *
 * Пул дистракторов плана — это ВСЕ термины плана, включая полку `hear`. Так среди трёх вариантов
 * ответа на «Could you tell me about your background?» оказывалась другая реплика того же
 * собеседника — «Are you ready to get started?». Это не неправильный ответ, это чужая роль: человек
 * готовится сказать вслух то, что говорят ЕМУ. Полка `hear` — ярус «понимаю» (канон §3), её реплики
 * не произносятся никогда, и в вариантах своего хода их не бывает вовсе.
 *
 * ## 2. Два семантически верных ответа — это монетка
 *
 * Каждая карточка дня называет умение сцены, которому служит (`skill_ref`, канон §8). Правильный
 * ответ служит умению ВОПРОСА; вариант с тем же `skill_ref` отвечает на тот же вопрос — и он тоже
 * верный. Отбирается такой вариант не по смыслу (проверить смысл нечем), а по адресу: дистрактор
 * обязан отвечать на ДРУГОЙ вопрос. Тогда в списке ровно один ответ, который сюда подходит, и
 * выбор снова что-то значит.
 *
 * ## Порядок и фолбэк
 *
 * Сначала своя сцена, потом остальные сцены плана: ближайший честный дистрактор — это фраза того же
 * эпизода, того же регистра, уже виденная. Если своя сцена дала мало — добираем из соседних, у
 * клиента для них уже есть латунная метка «из сцены N». В абракадабру не падаем и в каталог не
 * ходим: вариант вне плана — это фраза не из этого разговора.
 *
 * Дальше список уходит в обычный {@see \App\Modules\Vocabulary\Application\Query\DistractorReader}
 * со всеми его воротами — форма (вопрос среди вопросов), длина, синонимы, совпадение переводов, —
 * потому что «из какой полки» и «похож ли на ответ» это два разных вопроса, и второй уже решён.
 */
final class PlanAnswerOptions
{
    /** Полки, с которых человек ГОВОРИТ (канон §3, ярус «говорю»). */
    private const SPOKEN_SHELVES = ['say', 'ask'];

    /**
     * Полка, с которой человек ГОВОРИТ, — только у таких ходов варианты собираются этим правилом.
     *
     * Публично, потому что вызывающему надо знать это ДО того, как он полезет считать пул: слово,
     * связка, число и реплика собеседника собирают варианты по-своему, и подмена пула сломала бы им
     * карточку.
     */
    public static function isSpokenShelf(?string $shelf): bool
    {
        return in_array($shelf, self::SPOKEN_SHELVES, true);
    }

    /**
     * Кандидаты в варианты хода [$target], своей сценой вперёд.
     *
     * @param  array<int, list<SituationalCandidate>>  $scenes  карточки плана по индексу дня
     * @param  int|null  $ownDay  день сцены, которой принадлежит сам ход
     * @return list<string>  term id, в порядке предпочтения
     */
    public static function forTurn(SituationalCandidate $target, array $scenes, ?int $ownDay): array
    {
        // Своя сцена первой, остальные — по возрастанию дня, чтобы посадка была воспроизводимой.
        $order = array_keys($scenes);
        sort($order);
        if ($ownDay !== null) {
            $order = [$ownDay, ...array_values(array_filter($order, static fn (int $d): bool => $d !== $ownDay))];
        }

        $ids = [];
        foreach ($order as $day) {
            foreach ($scenes[$day] ?? [] as $candidate) {
                if ($candidate->termId === $target->termId) {
                    continue;
                }
                if (! self::isSpokenShelf($candidate->shelf)) {
                    continue; // реплика роли, слово, связка, число — не ответ человека
                }
                if (self::answersTheSameQuestion($target, $candidate)) {
                    continue;
                }
                $ids[$candidate->termId] = true;
            }
        }

        return array_keys($ids);
    }

    /**
     * Обе карточки служат ОДНОМУ умению сцены — значит отвечают на один вопрос.
     *
     * Карточка без умения — это карточное нарушение, которое день уже посчитал (канон §8), но до
     * вариантов оно доезжает как `null`. Пропускать такую нельзя: два `null` рядом не значат «разные
     * вопросы», они значат «неизвестно», а неизвестность в этом месте — это снова монетка.
     */
    private static function answersTheSameQuestion(SituationalCandidate $target, SituationalCandidate $candidate): bool
    {
        return $target->skillRef === null
            || $candidate->skillRef === null
            || $target->skillRef === $candidate->skillRef;
    }
}
