<?php

declare(strict_types=1);

namespace App\Modules\Learning\Domain\Service;

use App\Modules\Learning\Domain\ValueObject\PlanStage;
use App\Modules\Learning\Domain\ValueObject\PlanTermStanding;

/**
 * КОГДА СЦЕНУ МОЖНО ПРОГОНЯТЬ ГОЛОСОМ — наряд SCENE-RUN, Ч.2.1.
 *
 * «C никогда не первый: страшно» (`docs/plan-dialogue.md` §5). Прогон убирает с экрана всё —
 * реплику, варианты, блоки, — и остаётся подсказка на языке поддержки. Просить произнести по
 * памяти фразу, которую человек ни разу не выбрал в разговоре, — это не сложная карточка, это
 * неотвечаемая.
 *
 * Правило поэтому одно и оно про ВСЮ сцену: каждый ход `you` прошёл ступень B хотя бы одним верным
 * выбором. Не «в среднем», не «большинство» — сцена прогоняется целиком, и один ход, которого
 * человек не видел, это место, где разговор встанет.
 *
 * ## Не собралась — значит её нет
 *
 * Ни заглушки «недоступно», ни серой строки на экране дня: человеку с ней нечего делать, а
 * счётчику дня она бы соврала. Секция просто не строится, и день считается без неё.
 *
 * ## Единственное исключение — последний день
 *
 * Перед событием прогоняются ВСЕ сцены, дозревшие и нет (наряд Ч.2.8): завтра стойка, и сцена, до
 * которой лестница не дошла, — это ровно то место, где будет страшно. Исключение принимает
 * вызывающий, а не это правило: гейт отвечает на один вопрос и не знает, какой сегодня день.
 */
final class PlanSceneRunGate
{
    /**
     * Прошёл ли ЭТОТ ход ступень B хотя бы одним верным выбором.
     *
     * Два способа, и оба означают одно: пара стоит ВЫШЕ ступени B (значит B закрыта целиком) или
     * стоит на B и хотя бы один шаг чек-листа закрыт. Второй — обычный случай в тот самый день,
     * когда прогон и должен случиться: ступень проходят за одну посадку, и к прогону она может быть
     * закрыта не до конца.
     */
    public static function turnIsReady(PlanTermStanding $standing): bool
    {
        if ($standing->stage !== PlanStage::A && $standing->stage !== PlanStage::B) {
            return true;
        }
        if ($standing->stage === PlanStage::A) {
            // Знакомство ещё идёт: выбирать в разговоре человек не начинал.
            return false;
        }

        foreach ($standing->checklist as $step) {
            if ($step['done']) {
                return true;
            }
        }

        return false;
    }

    /**
     * Собирается ли прогон этой сцены — по стойкам ВСЕХ её ходов `you`.
     *
     * Сцена без единого своего хода прогоном не бывает: прогонять нечего, и «все ноль ходов готовы»
     * — это утверждение, которое верно и бессмысленно одновременно.
     *
     * @param  list<PlanTermStanding>  $turns  стойки ходов `you` этой сцены
     */
    public static function sceneIsReady(array $turns): bool
    {
        if ($turns === []) {
            return false;
        }

        foreach ($turns as $standing) {
            if (! self::turnIsReady($standing)) {
                return false;
            }
        }

        return true;
    }
}
