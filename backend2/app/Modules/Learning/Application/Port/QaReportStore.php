namespace App\Modules\Learning\Application\Port;

/**
 * КУДА ЛОЖИТСЯ «ЖАЛОБА» С ТЕЛЕФОНА — наряд DAY-GATE-1, Ч.0.5.
 *
 * Один тап на экране, где что-то не так: снимок экрана, идентификаторы плана/дня/посадки/карточки/
 * этапа, последние строки журнала микрофона и версии обеих сторон. Не отчёт об ошибке в трекере, а
 * СЛЕПОК МОМЕНТА: живой прогон 07.09 стоил суток именно потому, что от поломки остались одни слова
 * владельца, и по ним нельзя было сказать даже того, какая карточка была на экране.
 *
 * НАРУЖУ НЕ УХОДИТ НИЧЕГО. Ни Notion, ни почты, ни трекера: файлы ложатся на диск того же
 * контейнера, что и API. Отчёт содержит снимок ЧУЖОГО экрана со всем, что на нём было, и любая
 * отправка такого наружу — решение, которое принимает владелец, а не эта труба.
 */
interface QaReportStore
{
    /**
     * Записать один отчёт и вернуть его идентификатор.
     *
     * @param  array<string, mixed>  $report  что прислал клиент, как есть
     * @param  string|null  $screenshotPng  сырой PNG или null — снимок мог не получиться, и это не
     *                                      повод потерять всё остальное
     * @return string идентификатор отчёта (ULID), он же имя пары файлов
     */
    public function put(array $report, ?string $screenshotPng): string;
}
