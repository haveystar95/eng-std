<?php

declare(strict_types=1);

namespace App\Modules\Learning\Application\Port;

use App\Modules\Shared\Domain\ValueObject\CollectionId;

/**
 * ЗАКАЗАТЬ ОЗВУЧКУ РЕПЛИК, КОТОРЫХ НЕ ХВАТАЕТ — из посадки, вне запроса.
 *
 * Порт живёт в Learning, а адаптер — в Generation, ровно как у {@see PlanOutlinePort}: Learning не
 * зависит от Generation (deptrac держит это правило), а «сколько стоит фраза и каким голосом её
 * читать» — вопрос Generation и ничей больше.
 *
 * ## Зачем посадке вообще это уметь
 *
 * Озвучка заказывалась в ОДНОМ месте — при генерации дня ({@see
 * \App\Modules\Generation\Application\Command\GeneratePlanDayHandler}). Значит день, написанный до
 * того, как труба появилась, не получал файлов никогда, и никто их больше не просил. Живьём это
 * выглядит хуже, чем «нет голоса»: экран-диалог показывает «Готовим озвучку» (кадр DL·08) и ждёт
 * вечно, потому что ждать ему нечего — заказа не было и не будет.
 *
 * Канон §7 обещает обратное: «никакая реплика не подаётся на слух, пока озвучка не готова» — это
 * про СЕКУНДЫ ожидания, а не про навсегда. Посадка знает, каких файлов не хватает (она их только
 * что искала, чтобы отдать адреса клиенту), и это единственное место, где недостача видна раньше,
 * чем её увидит человек.
 *
 * Идемпотентность держит обработчик: он покупает только те реплики, которых нет для ЭТОГО голоса
 * (`TermAudioReader::missingFor`), поэтому повторный заказ ничего не тратит. Тумблер трубы стоит в
 * диспетчере, поэтому выключенная труба и здесь означает «никто никуда не ходил».
 */
interface OrdersLineSpeech
{
    /**
     * @param  list<CollectionId>  $collectionIds  дни посадки, у которых чего-то не хватает
     */
    public function order(array $collectionIds): void;
}
